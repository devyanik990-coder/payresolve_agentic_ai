/**
 * =====================================================================
 * PayResolve AI — src/queue/queuePlaceholders.js
 * Phase 5.2–5.3 — deterministic placeholder cases
 * Phase 11.0 — dataset-based placeholder model
 * ---------------------------------------------------------------------
 * Module (TDD-01):        Investigation Queue Module
 * Blueprint area (§2/§3): src/queue/
 *
 * Purpose:
 *   The SINGLE source of the deterministic placeholder Investigation Cases
 *   used across the Dashboard — by the Investigation Queue and the Case
 *   Preview / Investigation Engine. Each category yields its OWN, unique
 *   set of cases; the SAME category ALWAYS yields the SAME cases with the
 *   SAME details — no randomization, no time dependence.
 *
 * Phase 11.0 — dataset model:
 *   Earlier phases built each case at runtime from many parallel
 *   `*_BY_INDEX` lookup arrays. That no longer scales. The cases are now
 *   defined DIRECTLY as one deterministic dataset (`PLACEHOLDER_CASES`):
 *   a frozen map of category → array of COMPLETE, self-contained case
 *   objects. `placeholderCasesForCategory(category)` simply returns the
 *   corresponding array.
 *
 *   This model is intentionally OPEN for extension: adding a new field to
 *   an investigation (e.g. Risk Score, Gateway Response Code, 3DS Status,
 *   Retry History, Fraud Signals) requires ONLY adding that key to the
 *   individual case object(s) — no change to the dataset architecture,
 *   the accessor functions, or any consumer. Likewise, expanding a
 *   category from 3 to 10 cases (a later phase) is just adding more
 *   objects to that category's array.
 *
 * Determinism guarantees:
 *   - The dataset is static, frozen data — identical output across calls
 *     and refreshes. No Math.random, no Date/now, no counters.
 *   - Cases are frozen value objects (read-only descriptors, FS-01 §6).
 *
 * Referenced documentation:
 *   PRD §13 (the five MVP categories); FS-03 §3.3 (case descriptor
 *   fields), §6 (columns), §10 (Case Preview sections); FS-06 §4 (domain
 *   identities); Implementation Blueprint v1.1 §3.5.
 * =====================================================================
 */

