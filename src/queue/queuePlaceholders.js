/**
 * Return the deterministic placeholder cases for a category.
 * @param {string|null|undefined} category the selected category label
 * @returns {ReadonlyArray<Object>} the frozen case array (empty if the
 *   category is unknown/absent — never fabricated for other categories)
 */
export function placeholderCasesForCategory(category) {
  return PLACEHOLDER_CASES[category] || EMPTY;
}

/** Shared frozen empty result for unknown/absent categories. */
const EMPTY = Object.freeze([]);

/**
 * Look up a single placeholder case by id within a category's dataset.
 * @param {string} category the category whose cases to search
 * @param {string} caseId the Case ID to find
 * @returns {Object|null} the frozen case, or null if not in that category
 */
export function findPlaceholderCase(category, caseId) {
  if (caseId == null) return null;
  return (
    placeholderCasesForCategory(category).find((c) => c.id === caseId) || null
  );
}
